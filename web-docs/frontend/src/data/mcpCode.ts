export const mcpQuickstartCode = [
  'import { createRuntime, createRequest } from "@aipack-ai/agent";',
  'import { createMcpPlugin } from "@aipack-ai/mcp";',
  '',
  '// 1. 声明外部 MCP Server（stdio / http / sse 三种传输）',
  'const mcp = createMcpPlugin({',
  '  servers: [',
  '    {',
  '      name: "github",',
  '      transport: {',
  '        type: "stdio",',
  '        command: "npx",',
  '        args: ["-y", "@modelcontextprotocol/server-github"],',
  '        env: { GITHUB_TOKEN: "${GITHUB_TOKEN}" }, // ${VAR} 于连接时展开',
  '      },',
  '      timeoutMs: 30_000,',
  '    },',
  '    {',
  '      name: "docs",',
  '      transport: {',
  '        type: "http",',
  '        url: "https://mcp.example.com/mcp",',
  '        headers: { Authorization: "Bearer ${MCP_TOKEN}" },',
  '      },',
  '    },',
  '  ],',
  '});',
  '',
  '// 2. 注入 Runtime —— MCP 工具在 beforeRun 阶段懒连接并注册（幂等）',
  'const runtime = createRuntime({ extensions: [...mcp.extensions] });',
  '',
  '// 3. 可选预热：提前握手（CLI 启动 / 明确需要首轮即用工具时）',
  'await mcp.ready();',
  '',
  '// 4. 模型直接看到并调用远端工具：github__create_issue / docs__search ...',
  'const result = await runtime.run(createRequest("用 GitHub 工具查一下最近的 issue"));',
  '',
  '// 诊断（连接失败 / 命名冲突均不阻断整体，单个 server 失败不影响其余）',
  'mcp.diagnostics.forEach((d) => console.warn(`[${d.type}] ${d.server}: ${d.message}`));',
  'await mcp.dispose(); // 关闭全部子进程 / HTTP 连接',
].join('\n');

