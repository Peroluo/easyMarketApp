export const mcpAdapterCode = [
  '// 远端工具 → 原生 Tool 的映射规则（Model 侧完全无感）',
  '//   name        `${toolPrefix ?? server.name}__${rawName}`   // 双下划线分隔',
  '//   description 原始描述 + " [mcp:<server>]" 来源标注',
  '//   parameters  inputSchema 原样透传（JSON Schema 与 agent 约定一致）',
  '//   permissions ["mcp:<server>"]，可经 McpServerConfig.permissions 覆盖',
  '//   execute     content blocks → ToolResult.content；isError → details.error',
  '',
  '// 例：name = "github" 的 server 暴露 create_issue / search_code，',
  '//     模型看到的是 github__create_issue / github__search_code（+ 内部 mcp_status）。',
  '',
  '// content 映射（MCP block → agent ContentBlock）：',
  '//   text    → TextContent',
  '//   image   → ImageContent（缺 data/mimeType 时降级为文本摘要）',
  '//   resource / audio / 未知 → 文本摘要（前向兼容）',
  '',
  '// 命名冲突：registry 注册前 Map 预检，冲突时产出 collision 诊断并跳过',
  '// （不依赖 registerTool 的静默覆盖）；用 toolPrefix 显式消解。',
].join('\n');

