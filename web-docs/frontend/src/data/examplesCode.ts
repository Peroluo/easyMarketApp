export const exCompressionCode = [
  '// ===== aipack-compression：策略管道上下文压缩 =====',
  '// 注意：compression 是可选的，默认关闭。动态 import 方式避免硬依赖。',
  'import {',
  '  createRuntime,',
  '  createRequest,',
  '  getBuiltinModel, adaptAiModel, createStreamFnFromAi,',
  '  createDefaultTransformers,',
  '} from "@aipack-ai/agent";',
  '',
  'async function main() {',
  '  const ai = getBuiltinModel("deepseek", "deepseek-chat");',
  '  const model = adaptAiModel(ai);',
  '',
  '  // 动态加载 compression（推荐）',
  '  const { createCompressionTransformer, loadCompressionConfig } = await import("@aipack-ai/compression");',
  '',
  '  // 基于默认配置 + 覆盖项构造压缩配置',
  '  // （未覆盖项使用默认值，也支持 AIPACK_COMPRESSION_* / AIPACK_TRIM_* 等环境变量覆盖）',
  '  const config = loadCompressionConfig({',
  '    // 统一预算：有效预算 = contextWindow - 输出预留(默认模型 maxTokens) - 安全边距(5%)',
  '    // 双水位：70% 预警（后台预压缩）→ 80% 触发 → 40% 压到位',
  '    budget: { triggerRatio: 0.80, targetRatio: 0.40 },',
  '    // Trim 无损裁剪：超大工具输出按 token 预算裁剪（保留头尾关键行）',
  '    trim: { toolResultMaxTokens: 2000, toolResultHeadLines: 10, toolResultTailLines: 10 },',
  '    // Summarize 有损摘要：旧消息 fork 模型摘要（超输入预算自动 map-reduce 分块）',
  '    summarize: { minResourcesToCompress: 4, protectedRecentCount: 6, forkMaxTokens: 2048 },',
  '    // Truncate 硬截断保底：仍超硬限时按工具对整体丢弃最旧非 pinned 资源',
  '    truncate: { minWorkingSet: 2 },',
  '    // 防止过度压缩：每 turn 限流 + 冷却退避（无永久禁用）',
  '    safety: { maxAttempts: 5, cooldownTurns: 3 },',
  '  });',
  '',
  '  const transformer = createCompressionTransformer({',
  '    config,',
  '    model,',
  '    streamFn: createStreamFnFromAi(ai),',
  '    contextWindow: ai.contextWindow,',
  '  });',
  '',
  '  // 可选：监听上下文耗尽事件（pinned/保护区本身超限、压不下去时）',
  '  // 检查点/换会话决策归调用方，压缩器只给建议',
  '  transformer.onContextExhausted((e) => {',
  '    console.log(e.reason, e.suggestedSessionId);',
  '    console.log(e.handoffDocument.slice(0, 200));',
  '  });',
  '',
  '  const runtime = createRuntime({',
  '    model,',
  '    streamFn: createStreamFnFromAi(ai),',
  '    systemPrompt: "你是一名架构师，正在协助设计大型系统。",',
  '    transformers: [',
  '      ...createDefaultTransformers(),',
  '      // 注入压缩转换器',
  '      transformer,',
  '    ],',
  '  });',
  '',
  '  // 之后正常使用 run() / stream()；压缩逻辑对调用方透明',
  '  await runtime.run(createRequest("开始设计：做一个电商系统的订单模块"));',
  '  await runtime.close();',
  '}',
].join('\n');

