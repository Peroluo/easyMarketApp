export const lfRobustCode = [
  '// 1. 上报失败不影响主流程：所有 Langfuse 调用吞错，经 onError 上报',
  'new LangfuseExtension({',
  '  onError: (err, where) => myLogger.warn("langfuse 上报失败", where, err),',
  '  // 默认实现：限频 console.warn（前 5 次全量，之后每 100 次一次）',
  '});',
  '',
  '// 2. 内存安全：inputs 经 JSON 序列化快照后上报（与运行态对象解引用，',
  '//    避免消息数组等大对象滞留内存）；超 maxInputBytes 截断',
  'new LangfuseExtension({ maxInputBytes: 65_536 }); // 默认 64KB，超出截断',
  '',
  '// 3. 防泄漏：活跃根 run 表上限，超出淘汰最旧并补报结束',
  'new LangfuseExtension({ maxActiveRuns: 1000 }); // 默认 1000',
  '',
  '// 4. 静默降级：无 transport 且无凭据（显式或 LANGFUSE_*）→ no-op，离线可用',
  '//    进程退出前主动刷出上报队列（SDK 内部批量排队）',
  'const transport = new LangfuseTransport({ publicKey, secretKey });',
  'process.on("beforeExit", () => transport.flush());',
].join('\n');

export const lfCustomTransportCode = [
  'import { LangfuseExtension, type TraceTransport, type TracedRun, type TracedRunConfig }',
  '  from "@aipack-ai/agent-langfuse";',
  '',
  '// TraceTransport：后端 run 的最小结构面（Langfuse 及私有部署上报实现均遵循此接口）',
  'class MyTransport implements TraceTransport {',
  '  createRoot(config: TracedRunConfig): TracedRun {',
  '    // 返回实现 TracedRun 的对象：id / postRun / patchRun / end / createChild',
  '    //   - postRun()/patchRun()：首次持久化 / 更新（Langfuse SDK 内部排队，可为空实现）',
  '    //   - end(outputs, error, endTime, metadata)：标记结束字段',
  '    //   - createChild(config)：创建子 run（chain / llm / tool / retriever）',
  '    return new MyRun(config);',
  '  }',
  '}',
  '',
  '// 注入后视为启用（优先于凭据判定），适合：',
  '//   - 单元测试离线 fake transport',
  '//   - 对接私有部署观测后端（复用 langfuse 数据模型）',
  'new LangfuseExtension({ transport: new MyTransport() });',
  '',
  '// 也支持注入既有 Langfuse 实例（复用全局实例 / 测试替身；注入后忽略凭据参数）',
  'new LangfuseTransport({ client: existingLangfuseClient });',
].join('\n');

