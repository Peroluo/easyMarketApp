  'import {',
  '  createRuntime,',
  '  createRequest,',
  '  getBuiltinModel,',
  '  adaptAiModel,',
  '  createStreamFnFromAi,',
  '} from "@aipack-ai/agent";',
  '',
  'const runtime = createRuntime({',
  '  model: adaptAiModel(getBuiltinModel("deepseek", "deepseek-chat")),',
  '  streamFn: createStreamFnFromAi(getBuiltinModel("deepseek", "deepseek-chat")),',
  '  systemPrompt: "你是天气助手。需要查天气时调用工具，否则直接回答。",',
  '  tools: [',
  '    {',
  '      name: "get_weather",',
  '      description: "查询指定城市的当前天气信息",',
  '      // 使用 TypeBox 声明参数，自动转为 JSON Schema',
  '      parameters: Type.Object(',
  '        {',
  '          city: Type.String({ description: "城市名称，如 北京" }),',
  '          unit: Type.Union(',
  '            [Type.Literal("c"), Type.Literal("f")],',
  '            { description: "温度单位：摄氏/华氏", default: "c" },',
  '          ),',
  '        },',
  '        { additionalProperties: false },',
  '      ),',
  '      // 工具执行函数：(id, args) => ToolResult',
  '      execute: async (id, args) => {',
  '        console.log("[get_weather] 被调用, 参数=", args);',
  '        // 实际项目中这里调用真实天气 API',
  '        const data: Record<string, string> = {',
  '          "北京": "晴，25°C",',
  '          "上海": "多云，23°C",',
  '          "广州": "阵雨，28°C",',
  '        };',
  '        const key = String(args.city);',
