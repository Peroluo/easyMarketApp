export const skillsDiyCode = [
  'import { createRuntime } from "@aipack-ai/agent";',
  'import { SkillsExtension, createSkillTool, formatSkillsSection } from "@aipack-ai/skills";',
  '',
  '// 方式一：直接用 Extension（跳过文件加载，程序化提供 skill）',
  'const runtime1 = createRuntime({',
  '  extensions: [',
  '    new SkillsExtension([',
  '      { name: "demo", description: "演示 skill", content: "# Demo\\n步骤..." },',
  '    ], {',
  '      toolName: "skill",     // 工具名，默认 skill',
  '      registerTool: true,    // 是否注册内置 skill 工具，默认 true',
  '      injectPrompt: true,    // 是否注入目录段，默认 true',
  '    }),',
  '  ],',
  '});',
  '',
  '// 方式二：只用纯函数，完全 DIY（prompt 拼接 / 工具注册由你决定）',
  'const tool = createSkillTool(skills);                 // 独立工具工厂',
  'const section = formatSkillsSection(skills);          // 目录段渲染',
  'runtime.registerTool(tool);',
  'runtime.setSystemPrompt(basePrompt + "\\n\\n" + section);',
].join('\n');

export const skillsDiagnosticsCode = [
  'import { loadSkills } from "@aipack-ai/skills";',
  '',
  'const { skills, diagnostics } = loadSkills({ cwd: process.cwd() });',
  '',
  'for (const d of diagnostics) {',
  '  // type: "error"     → 校验失败被跳过（name/description/content 不合规）',
  '  // type: "collision" → 同名冲突，先注册者胜（user 优先于 project）',
  '  // type: "warning"   → 非致命问题（目录读取失败 / extraPath 不存在）',
  '  console.warn(`[${d.type}] ${d.message} (${d.path ?? ""})`);',
  '}',
  '',
  '// 健壮性约定：加载失败 / 校验失败只产诊断不中断，',
  '// Runtime 启动不会被单个坏 skill 阻塞。',
].join('\n');
